// Generates src/data/mapGeometry.ts from Natural Earth 1:50m (world-atlas).
// Run with `npm run map` after changing the bounds or the country list.
import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { geoMercator, geoPath } from 'd3-geo'
import { feature, mesh } from 'topojson-client'

const require = createRequire(import.meta.url)
const world = require('world-atlas/countries-50m.json')

const WIDTH = 300
const BOUNDS = { west: 33.95, east: 36.15, south: 29.4, north: 33.45 }
const COUNTRIES = { 376: 'Israel', 275: 'Palestine', 422: 'Lebanon', 760: 'Syria', 400: 'Jordan', 818: 'Egypt', 682: 'Saudi Arabia' }

const box = { type: 'MultiPoint', coordinates: [[BOUNDS.west, BOUNDS.north], [BOUNDS.east, BOUNDS.south]] }
const projection = geoMercator().fitWidth(WIDTH, box)
const [, top] = projection([BOUNDS.west, BOUNDS.north])
const [, bottom] = projection([BOUNDS.west, BOUNDS.south])
projection.translate([projection.translate()[0], projection.translate()[1] - top])
const HEIGHT = Math.round(bottom - top)
projection.clipExtent([[-5, -5], [WIDTH + 5, HEIGHT + 5]])

const path = geoPath(projection).digits(1)
const obj = world.objects.countries
const wanted = obj.geometries.filter(g => g.id in COUNTRIES)
const land = wanted.map(g => ({ id: g.id, d: path(feature(world, g)) })).filter(c => c.d)
const borders = path(mesh(world, { ...obj, geometries: wanted }, (a, b) => a !== b))

const out = `// Generated by scripts/build-map.mjs from Natural Earth 1:50m. MUST NOT be edited by hand.
export const MAP_W = ${WIDTH}
export const MAP_H = ${HEIGHT}
/** Web Mercator parameters matching the paths below. */
export const PROJECTION = { scale: ${projection.scale()}, tx: ${projection.translate()[0]}, ty: ${projection.translate()[1]} }
export const LAND: { id: string; d: string }[] = ${JSON.stringify(land)}
export const BORDERS = ${JSON.stringify(borders)}
`
writeFileSync(new URL('../src/data/mapGeometry.ts', import.meta.url), out)
console.log('map', WIDTH, 'x', HEIGHT, (out.length / 1024).toFixed(1) + ' kB')
